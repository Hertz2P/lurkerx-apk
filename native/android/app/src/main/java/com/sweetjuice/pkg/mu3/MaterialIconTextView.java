    public MaterialIconTextView(Context context) {
        super(context);
        init(context, null);
    }

    public MaterialIconTextView(Context context, AttributeSet attrs) {
        super(context, attrs);
        init(context, attrs);
    }

    public MaterialIconTextView(Context context, AttributeSet attrs, int defStyleAttr) {
        super(context, attrs, defStyleAttr);
        init(context, attrs);
    }

    private void init(Context context, AttributeSet attrs) {
        if (typeface == null) {
            try {
                typeface = Typeface.createFromAsset(context.getAssets(), "fonts/MaterialSymbolsOutlined.ttf");
            } catch (Exception e) {
                typeface = Typeface.DEFAULT;
            }
        }
        setTypeface(typeface);
        setGravity(Gravity.CENTER);
        setSingleLine(true);
    }

    public void setIconName(String name) {
        String cp = CODEPOINTS.get(name);
        if (cp != null) {
            setText(new String(Character.toChars(Integer.parseInt(cp, 16))));
        } else {
            setText("");
        }
    }
